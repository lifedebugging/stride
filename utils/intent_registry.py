import re

# Precompiled exact-match and phrase-match indexes for O(1)/O(n) lookup
_EXACT_INDEX = {}
_PHRASE_INDEX = []   # list of (keyword, category) sorted by keyword length desc

for _cat, _data in INTENT_REGISTRY.items():
    for _kw in _data["keywords"]:
        _EXACT_INDEX[_kw] = _cat
        _PHRASE_INDEX.append((_kw, _cat))
_PHRASE_INDEX.sort(key=lambda x: len(x[0]), reverse=True)

_WORD_RE = re.compile(r"[a-z0-9']+")


def classify_intent(query):
    """Classify a query string into an intent category.

    Returns a dict with category name, model, tool, priority, and matched
    keyword, or None if no confident match (fall through to semantic search).
    Matching: exact match on the normalized query first; otherwise substring
    (phrase) match with word boundaries, longest keyword wins; ties broken
    by lowest priority number.
    """
    if not query or not query.strip():
        return None
    normalized = " ".join(query.strip().lower().split())

    # 1) Exact match (highest confidence)
    cat = _EXACT_INDEX.get(normalized)
    if cat:
        d = INTENT_REGISTRY[cat]
        return {"intent": cat, "name": d["name"], "model": d["model"],
                "tool": d["tool"], "priority": d["priority"],
                "match": normalized, "exact": True}

    # 2) Phrase match: check longest keywords first, require word boundaries
    words = set(_WORD_RE.findall(normalized))
    best = None  # (priority, category, keyword)
    for kw, cat in _PHRASE_INDEX:
        if kw in normalized:
            # word-boundary guard: keyword must align to token edges
            start = normalized.find(kw)
            end = start + len(kw)
            left_ok = start == 0 or normalized[start - 1] == " "
            right_ok = end == len(normalized) or normalized[end] == " "
            if not (left_ok and right_ok):
                continue
            prio = INTENT_REGISTRY[cat]["priority"]
            if best is None or prio < best[0]:
                best = (prio, cat, kw)
            break  # longest match already found first; keep it
    if best:
        _, cat, kw = best
        d = INTENT_REGISTRY[cat]
        return {"intent": cat, "name": d["name"], "model": d["model"],
                "tool": d["tool"], "priority": d["priority"],
                "match": kw, "exact": False}
    return None

